import sys, os
G = {}
def g(ch, rows): G[ch] = rows.split()
g('0', '.###. #...# #..## #.#.# ##..# #...# .###.')
g('1', '..#.. .##.. ..#.. ..#.. ..#.. ..#.. .###.')
g('2', '.###. #...# ....# ...#. ..#.. .#... #####')
g('3', '#####  ...#. ..#.. ...#. ....# #...# .###.'.replace('  ', ' '))
g('4', '...#. ..##. .#.#. #..#. ##### ...#. ...#.')
g('5', '##### #.... ####. ....# ....# #...# .###.')
g('6', '..##. .#... #.... ####. #...# #...# .###.')
g('7', '##### ....# ...#. ..#.. .#... .#... .#...')
g('8', '.###. #...# #...# .###. #...# #...# .###.')
g('9', '.###. #...# #...# .#### ....# ...#. .##..')
g('.', '..... ..... ..... ..... ..... .##.. .##..')
g('-', '..... ..... ..... ##### ..... ..... .....')
g('%', '##..# ##..# ...#. ..#.. .#... #..## #..##')
g('/', '....# ....# ...#. ..#.. .#... #.... #....')
g(':', '..... .##.. .##.. ..... .##.. .##.. .....')
g('^', '.##.. #..#. #..#. .##.. ..... ..... .....')
g('A', '.###. #...# #...# ##### #...# #...# #...#')
g('C', '.###. #...# #.... #.... #.... #...# .###.')
g('D', '####. #...# #...# #...# #...# #...# ####.')
g('E', '##### #.... #.... ####. #.... #.... #####')
g('G', '.###. #...# #.... #.### #...# #...# .####')
g('H', '#...# #...# #...# ##### #...# #...# #...#')
g('I', '.###. ..#.. ..#.. ..#.. ..#.. ..#.. .###.')
g('K', '#...# #..#. #.#.. ##... #.#.. #..#. #...#')
g('M', '#...# ##.## #.#.# #.#.# #...# #...# #...#')
g('N', '#...# ##..# #.#.# #..## #...# #...# #...#')
g('O', '.###. #...# #...# #...# #...# #...# .###.')
g('P', '####. #...# #...# ####. #.... #.... #....')
