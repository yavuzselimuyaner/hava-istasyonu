g('Y', '#...# #...# .#.#. ..#.. ..#.. ..#.. ..#..')
g('Z', '##### ....# ...#. ..#.. .#... #.... #####')
for ch, r in G.items():
    assert len(r) == 7 and all(len(x) == 5 for x in r), (ch, r)
if '--preview' in sys.argv:
    for ch in '0123456789.-%/:^ACDEGHIKMNOPRSTUZ':
        print(ch); print('\n'.join(x.replace('.', ' ').replace('#', '@') for x in G[ch])); print()
    sys.exit()
first, last = 32, 94
lines = ['#pragma once', '#include <stdint.h>', '/* uretilen dosya: tools/gen_font.py. Sutun bazli, bit0 = ust satir. ASCII 32..94; ^ = derece isareti */',
         '#define FONT_FIRST %d' % first, '#define FONT_LAST %d' % last,
         'static const uint8_t font5x7[][5] = {']
for c in range(first, last + 1):
    ch = chr(c)
    cols = [0] * 5
    if ch in G:
        for y, row in enumerate(G[ch]):
            for x, px in enumerate(row):
                if px == '#':
                    cols[x] |= 1 << y
    label = 'bs' if ch == chr(92) else ch
    lines.append('    {%s}, /* %s */' % (', '.join('0x%02X' % v for v in cols), label))
lines.append('};')
open(os.path.join(os.path.dirname(__file__), '..', 'main', 'font5x7.h'), 'w', encoding='utf8').write('\n'.join(lines) + '\n')
print('yazildi, karakter:', len(G))
